import { test, expect } from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'

test.describe('Canvas workspace', () => {
  test('zooms, pans, resets and leaves the toolbar fixed', async ({ page }) => {
    await page.goto('/')
    const tools = page.getByRole('navigation', { name: 'Canvas tools' })
    const before = await tools.boundingBox()
    const scene = page.locator('.aura-space')
    const world = page.getByTestId('canvas-world')
    const contentBounds = await world.boundingBox()
    const gridBefore = await scene.evaluate((element) => getComputedStyle(element).backgroundSize)
    await page.keyboard.press('-')
    expect(await scene.evaluate((element) => getComputedStyle(element).backgroundSize)).not.toBe(gridBefore)
    await page.mouse.move(20, 180)
    await page.mouse.down()
    await page.mouse.move(120, 230, { steps: 5 })
    await page.mouse.up()
    await expect(scene).toHaveCSS('background-position', '100px 50px')
    expect(await world.boundingBox()).toEqual(contentBounds)
    expect(await tools.boundingBox()).toEqual(before)
    await page.keyboard.press('0')
    await expect(scene).toHaveCSS('background-position', '0px 0px')
    await page.mouse.move(20, 180)
    await page.keyboard.down('Control')
    await page.mouse.wheel(0, -50)
    await page.keyboard.up('Control')
    await expect.poll(() => scene.evaluate((element) => getComputedStyle(element).backgroundSize)).not.toBe(gridBefore)
  })

  test('settings keeps the writing and camera in place and restores gear focus', async ({ page }) => {
    await page.goto('/mirror')
    await page.getByRole('textbox').fill('SYNTHETIC_CANVAS_DRAFT')
    await page.mouse.move(20, 180)
    await page.mouse.wheel(0, 40)
    await expect(page.locator('.aura-space')).toHaveCSS('background-position', '0px -40px')
    const transform = await page.locator('.aura-space').getAttribute('style')
    const gear = page.getByRole('button', { name: 'Settings', exact: true })
    await gear.click()
    const panel = page.getByRole('dialog', { name: 'Settings', exact: true })
    await expect(panel).toBeVisible()
    const privacy = page.getByRole('button', { name: 'Privacy & device', exact: true })
    await privacy.focus()
    await page.keyboard.press('Enter')
    await expect(privacy).toHaveAttribute('aria-expanded', 'true')
    await expect(page.getByRole('button', { name: 'Clear device data', exact: true })).toBeVisible()
    await expect(page).toHaveURL('/mirror')
    await page.getByRole('switch', { name: 'Reduce motion', exact: true }).click()
    await page.getByRole('button', { name: 'Close settings' }).click()
    await expect(panel).not.toBeVisible()
    await expect(gear).toBeFocused()
    await expect(page.getByRole('textbox')).toHaveValue('SYNTHETIC_CANVAS_DRAFT')
    expect(await page.locator('.aura-space').getAttribute('style')).toBe(transform)
    await gear.click()
    await expect(page.getByRole('switch', { name: 'Reduce motion', exact: true })).toBeChecked()
    await page.keyboard.press('Escape')
    await expect(panel).not.toBeVisible()
  })

  test('supports accessible light and dark scenes and remembers appearance', async ({ page }) => {
    await page.emulateMedia({ colorScheme: 'light', reducedMotion: 'reduce' })
    await page.goto('/')
    for (const theme of ['light', 'dark']) {
      if (theme === 'dark') await page.getByRole('button', { name: 'Switch to dark mode' }).click()
      await expect(page.locator('.aura-space')).toHaveAttribute('data-theme', theme)
      await page.evaluate(async () => {
        await document.fonts.ready
        await new Promise<void>((done) => requestAnimationFrame(() => requestAnimationFrame(() => done())))
      })
      let result = await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa', 'wcag22aa']).analyze()
      expect(result.violations.map(({ id, nodes }) => ({ id, targets: nodes.map(({ target, failureSummary }) => ({ target, failureSummary })) }))).toEqual([])
      await page.getByRole('button', { name: 'Settings', exact: true }).click()
      result = await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa', 'wcag22aa']).analyze()
      expect(result.violations.map(({ id, nodes }) => ({ id, targets: nodes.map(({ target, failureSummary }) => ({ target, failureSummary })) }))).toEqual([])
      await page.keyboard.press('Escape')
      await expect(page.getByRole('dialog', { name: 'Settings', exact: true })).not.toBeVisible()
    }
    await page.reload()
    await expect(page.locator('.aura-space')).toHaveAttribute('data-theme', 'dark')
  })
})
